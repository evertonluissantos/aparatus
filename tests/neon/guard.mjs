import { readFileSync, realpathSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { readRemoteEnvironment, verifyAuthorization, NeonSafetyError } from "./identity.mjs";
import { restrictNeonNetwork } from "./network-guard.mjs";

if (process.env.NODE_ENV !== "test" || process.env.CORTZ_TEST_MODE !== "postgres-neon") throw new NeonSafetyError("NEON_WORKER_NOT_AUTHORIZED");
const remote = readRemoteEnvironment(process.env);
const trust = JSON.parse(readFileSync(new URL("./trusted-projects.json", import.meta.url), "utf8"));
const envelope = JSON.parse(readFileSync(remote.authorizationFile,"utf8"));
export const manifest = verifyAuthorization(envelope,trust,remote);
export const testSchema = process.env.CORTZ_NEON_RUN_SCHEMA;
if (!/^cortz_run_[a-f0-9]{32}$/.test(testSchema ?? "")) throw new NeonSafetyError("TEST_SCHEMA_INVALID");
// Job directory is generated by launcher, never an arbitrary import path.
const root = realpathSync(process.env.CORTZ_NEON_CLIENT_ROOT);
const expectedParent = fileURLToPath(new URL("../",import.meta.url));
if (!root.startsWith(join(realpathSync(expectedParent),".neon-generated-"))) throw new NeonSafetyError("CLIENT_PATH_INVALID");
const marker=JSON.parse(readFileSync(join(root,"owner.json"),"utf8"));
if (marker.schema !== testSchema || marker.authorizationId !== manifest.authorizationId || marker.verifiedProjectId !== manifest.projectId || !Number.isFinite(marker.verifiedAt) || Date.now() - marker.verifiedAt > 30_000 || marker.verifiedAt > Date.now()) throw new NeonSafetyError("CLIENT_PATH_OR_VERIFICATION_INVALID");
export const configuration = Object.freeze({ ...remote.connection, options: `-c search_path=${testSchema} -c lock_timeout=10000 -c statement_timeout=20000` });
export const isolatedClientPath = join(root,"client","client.js");
restrictNeonNetwork(manifest.hostname);
